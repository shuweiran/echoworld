#!/usr/bin/env node
/**
 * export_assets.js — 导出构建（Node 运行一次）
 *   1) js/assets_embedded.js：把 assets/*.png|json 编码为 base64 data URI
 *      （file:// 打开时浏览器禁止本地 XHR，Phaser 加载器改用内嵌资源兜底；
 *        http 打开时走 assets/ 真实文件管线）
 *   2) maps/manor.json、maps/bsp-sample.json：契约 JSON 规范副本
 *      （map_contract.js 内嵌副本为 file:// 兜底，maps/*.json 为规范文件，
 *        阶段 2 LLM 生成路径/外部消费者以 maps/*.json 为准）
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const assetsDir = path.join(root, 'assets');
const jsDir = path.join(root, 'js');
const mapsDir = path.join(root, 'maps');
fs.mkdirSync(jsDir, { recursive: true });
fs.mkdirSync(mapsDir, { recursive: true });

// 1) 内嵌资源
const files = fs.readdirSync(assetsDir).filter((f) => /\.(png|json)$/.test(f)).sort();
const entries = {};
for (const f of files) {
  const buf = fs.readFileSync(path.join(assetsDir, f));
  const mime = f.endsWith('.png') ? 'image/png' : 'application/json';
  entries[f] = 'data:' + mime + ';base64,' + buf.toString('base64');
}
const js = [
  '/** GENERATED by tools/export_assets.js — 勿手改 */',
  '// file:// 模式下的内嵌资源（base64 data URI），http 模式不使用（走 assets/ 真实文件）',
  '(function (global) {',
  '  global.PHASER_DEMO_EMBEDDED = ' + JSON.stringify(entries, null, 1) + ';',
  "  if (typeof module !== 'undefined' && module.exports) { module.exports = global.PHASER_DEMO_EMBEDDED; }",
  "})(typeof window !== 'undefined' ? window : this);",
  '',
].join('\n');
fs.writeFileSync(path.join(jsDir, 'assets_embedded.js'), js, 'utf8');

// 2) 契约 JSON 规范副本
const MAP = require(path.join(jsDir, 'map_contract.js'));
const Bsp = require(path.join(jsDir, 'bsp.js'));
fs.writeFileSync(path.join(mapsDir, 'manor.json'), JSON.stringify(MAP.manor, null, 1) + '\n', 'utf8');
const bspMap = Bsp.generateBspMap({ width: 24, height: 16, seed: 20260801 });
fs.writeFileSync(path.join(mapsDir, 'bsp-sample.json'), JSON.stringify(bspMap, null, 1) + '\n', 'utf8');

console.log('exported:');
console.log('  js/assets_embedded.js (' + files.length + ' files, ' + Math.round(js.length / 1024) + ' KB)');
console.log('  maps/manor.json (' + fs.statSync(path.join(mapsDir, 'manor.json')).size + ' B)');
console.log('  maps/bsp-sample.json (' + fs.statSync(path.join(mapsDir, 'bsp-sample.json')).size + ' B)');
